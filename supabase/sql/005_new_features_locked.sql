-- 005_new_features_locked.sql : ล็อกระบบใหม่ทั้งหมดให้เห็นเฉพาะยศที่แอดมินเลือก
-- วิธีใช้: รันหลัง 004 (Supabase → SQL Editor → New query → วาง → Run)
-- รันซ้ำได้ ไม่พัง และไม่ทับค่าที่แอดมินตั้งไว้แล้ว
--
-- ระบบใหม่ที่ล็อกตั้งแต่เริ่ม (ยังไม่มียศ = มีแค่แอดมินที่เห็น):
--   mails       เก็บเมล+รหัส
--   plain_notes โน๊ตทั่วไป
--   chat        แชทเก็บข้อความ
--   calendar    ปฏิทิน
-- (ช่องค้นหาเป็นส่วนกลางของแอพ ไม่ล็อก แต่ค้นเจอเฉพาะระบบที่ตัวเองมีสิทธิ์)
--
-- แอดมินไปติ๊กยศให้แต่ละระบบได้ที่ หน้าตั้งค่า → ยศ
-- ส่วนตารางของแต่ละระบบ อยู่ในไฟล์ 006 เป็นต้นไป (ไฟล์ละระบบ)
-- =====================================================================

insert into public.feature_rules (feature_id, is_locked) values
  ('mails', true),
  ('plain_notes', true),
  ('chat', true),
  ('calendar', true)
on conflict (feature_id) do nothing;
